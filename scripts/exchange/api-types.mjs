// Generate TypeScript types for the Exchange core's API from its committed OpenAPI schema.
//
//   node scripts/exchange/api-types.mjs [path/to/openapi.json]    (npm run exchange:types)
//
// The default schema is the core repository's docs/api/openapi.json beside this repository
// (Desktop/3dExchange next to Desktop/Exchange-Shell). It writes src/exchange/api.gen.ts: one
// interface per schema and `Routes`, the GET routes under /api/v1 with their path and query
// parameters and response. It covers the JSON Schema the core's FastAPI models produce (objects,
// arrays, $ref, nullable anyOf, enums, constants and maps); anything else fails loudly.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const input = path.resolve(process.argv[2] || path.join(root, '..', '3dExchange', 'docs', 'api', 'openapi.json'));
const output = path.join(root, 'src', 'exchange', 'api.gen.ts');
const schema = JSON.parse(readFileSync(input, 'utf8'));
const PREFIX = '/api/v1';

const quote = name => /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
const comment = (text, indent = '') => text ? `${indent}/** ${text.replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim()} */\n` : '';

function type(node, where) {
  // A schema with only a title or description is Python's Any.
  const structural = ['$ref', 'const', 'enum', 'anyOf', 'oneOf', 'type', 'items', 'properties', 'additionalProperties'];
  if (!node || !structural.some(key => key in node)) return 'unknown';
  if (node.$ref) return node.$ref.split('/').pop();
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ');
  if (node.anyOf || node.oneOf) return [...new Set((node.anyOf || node.oneOf).map(item => type(item, where)))].join(' | ');
  switch (node.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${wrap(type(node.items, where))}[]`;
    case 'object':
      if (node.properties) return inline(node, where);
      if (node.additionalProperties && node.additionalProperties !== true) return `Record<string, ${type(node.additionalProperties, where)}>`;
      return 'Record<string, unknown>';
  }
  throw new Error(`${where}: unsupported schema ${JSON.stringify(node).slice(0, 120)}`);
}
const wrap = text => /[|&]/.test(text) ? `(${text})` : text;

function inline(node, where, indent = '  ') {
  const required = new Set(node.required || []);
  const lines = Object.entries(node.properties).map(([name, value]) =>
    `${comment(value.description, indent)}${indent}${quote(name)}${required.has(name) ? '' : '?'}: ${type(value, `${where}.${name}`)}`);
  return `{\n${lines.join('\n')}\n${indent.slice(2)}}`;
}

let out = `// Generated by scripts/exchange/api-types.mjs from the Exchange core's docs/api/openapi.json
// (API ${schema.info.version}). Do not edit by hand; run npm run exchange:types after the core's API changes.
/* eslint-disable */

`;
for (const [name, node] of Object.entries(schema.components?.schemas || {})) {
  out += comment(node.description);
  out += node.type === 'object' && node.properties ? `export interface ${name} ${inline(node, name)}\n\n` : `export type ${name} = ${type(node, name)}\n\n`;
}

const routes = [];
for (const [route, operations] of Object.entries(schema.paths)) {
  if (!route.startsWith(`${PREFIX}/`) || !operations.get) continue;
  const op = operations.get, key = route.slice(PREFIX.length + 1);
  const params = op.parameters || [];
  const group = where => params.filter(p => p.in === where).map(p =>
    `${comment(p.description || p.schema?.description, '      ')}      ${quote(p.name)}${p.required ? '' : '?'}: ${type(p.schema, `${key}.${p.name}`)}`);
  const json = op.responses?.['200']?.content?.['application/json']?.schema;
  const block = lines => lines.length ? `{\n${lines.join('\n')}\n    }` : '{}';
  routes.push(`${comment(op.description || op.summary, '  ')}  ${JSON.stringify(key)}: {\n    path: ${block(group('path'))}\n    query: ${block(group('query'))}\n    response: ${json ? type(json, key) : 'Blob'}\n  }`);
}
out += `/** The core's GET routes under ${PREFIX}, proxied by the shell as /api/exchange/<route>. */\nexport interface Routes {\n${routes.join('\n')}\n}\n`;
writeFileSync(output, out);
console.log(`Wrote ${path.relative(root, output)}: ${Object.keys(schema.components?.schemas || {}).length} types, ${routes.length} routes (from ${input})`);
